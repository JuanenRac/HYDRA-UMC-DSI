    final arb = json.decode(File('lib/l10n/app_en.arb').readAsStringSync())
        as Map<String, dynamic>;
    final keys = arb.keys.where((k) => !k.startsWith('@')).toSet();
    expect(_texts.keys.toSet().difference(keys), isEmpty, reason: 'removed key');
    expect(keys.difference(_texts.keys.toSet()), isEmpty, reason: 'new key');
  });

  test('The app supports the eight languages of the ecosystem', () {
    expect(
      AppLocalizations.supportedLocales.map((l) => l.languageCode).toSet(),
      _languages.toSet(),
    );
  });

  for (final code in _languages) {
    test('Language $code answers every text', () async {
      final l = await AppLocalizations.delegate.load(Locale(code));
      expect(l.localeName, code);
      for (final entry in _texts.entries) {
        final text = entry.value(l);
        expect(text.trim(), isNotEmpty, reason: '$code/${entry.key}');
      }
    });
  }
}
